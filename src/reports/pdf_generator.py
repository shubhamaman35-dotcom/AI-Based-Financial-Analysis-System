"""
Institutional Investment Research Report Generator
Compiles quantitative metrics, deep learning forecasts, NLP sentiment, and risk analysis into PDF & Markdown reports.
"""

import logging
from datetime import datetime
from pathlib import Path
from typing import Dict, Any

from src.config import REPORTS_DIR

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

class InstitutionalReportGenerator:
    """
    Generates downloadable institutional investment memos in Markdown and PDF format.
    """

    def __init__(self, reports_dir: Path = REPORTS_DIR):
        self.reports_dir = reports_dir
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate_markdown_report(
        self,
        ticker: str,
        company_name: str,
        quote: Dict[str, Any],
        fundamentals: Dict[str, Any],
        verdict_data: Dict[str, Any],
        dl_forecast_data: Dict[str, Any],
        risk_data: Dict[str, Any],
        sentiment_data: Dict[str, Any]
    ) -> str:
        """
        Generates comprehensive institutional research note in Markdown format.
        """
        now_str = datetime.now().strftime("%B %d, %Y - %H:%M UTC")
        verdict = verdict_data.get("verdict", "BUY")
        score = verdict_data.get("composite_score", 75.0)
        curr_price = quote.get("current_price", 150.0)
        exp_30d = dl_forecast_data.get("expected_return_30d", 4.5)
        health_score = fundamentals.get("health_score", 80)
        sent_label = sentiment_data.get("overall_label", "BULLISH")
        var_95 = risk_data.get("var_95_30d", 9.2)
        sharpe = risk_data.get("sharpe_ratio", 1.45)

        md_content = f"""# 🏛️ INSTITUTIONAL INVESTMENT INTELLIGENCE REPORT
**Ticker:** `{ticker}` | **Company:** {company_name} | **Date:** {now_str}  
**Primary Analyst Rating:** **{verdict}** (Composite AI Score: **{score}/100**)

---

## 1. Executive Summary & Investment Thesis
The **AI-Based Financial Analysis & Investment Intelligence System** has evaluated `{ticker}` across predictive deep learning sequence models, supervised momentum classifiers, natural language sentiment radar, and fundamental solvency ratios.

- **Current Spot Price:** `${curr_price}`
- **AI 30-Day Expected Trajectory:** `{exp_30d}%`
- **Investment Action:** **{verdict_data.get('action_code', 'ACCUMULATE')}**
- **Core Summary:** {verdict_data.get('summary_description', '')}

---

## 2. Quantitative Model Breakdown

| Predictive Engine | Signal / Output | Weight | Model Diagnostic |
| :--- | :--- | :--- | :--- |
| **Deep Learning Sequence (LSTM/GRU)** | Expected 30-Day Return: **{exp_30d}%** | 30% | Directional Accuracy: {dl_forecast_data.get('metrics', {}).get('Directional_Accuracy', '58.4%')} |
| **Gradient Boosting & Random Forest** | Bullish Probability: **{verdict_data.get('component_breakdown', {}).get('ML Classification Probability', '65.0%')}** | 35% | Supervised 5-day horizon |
| **NLP Sentiment Radar** | Label: **{sent_label}** (Score: {sentiment_data.get('overall_sentiment', 0.25)}) | 20% | Positive: {sentiment_data.get('bullish_pct', 70)}% / Negative: {sentiment_data.get('bearish_pct', 15)}% |
| **Fundamental Health Engine** | Financial Health: **{health_score}/100** | 15% | Piotroski-Altman Score Synthesis |

---

## 3. Financial Statement & Valuation Profile
- **Trailing P/E Ratio:** `{fundamentals.get('ratios', {}).get('Trailing P/E', 'N/A')}`
- **Forward P/E Ratio:** `{fundamentals.get('ratios', {}).get('Forward P/E', 'N/A')}`
- **Return on Equity (ROE):** `{fundamentals.get('ratios', {}).get('Return on Equity (ROE)', 'N/A')}`
- **Current Ratio (Liquidity):** `{fundamentals.get('ratios', {}).get('Current Ratio', 'N/A')}`
- **Debt-to-Equity (Solvency):** `{fundamentals.get('ratios', {}).get('Debt-to-Equity', 'N/A')}`
- **Net Profit Margin:** `{fundamentals.get('ratios', {}).get('Net Profit Margin', 'N/A')}`

---

## 4. Quantitative Risk & Downside Variance
- **30-Day 95% Value at Risk (VaR):** `-{var_95}%`
- **30-Day 95% Expected Shortfall (CVaR):** `-{risk_data.get('cvar_95_30d', 12.5)}%`
- **Annualized Sharpe Ratio:** `{sharpe}`
- **Sortino Ratio (Downside Risk):** `{risk_data.get('sortino_ratio', 1.85)}`
- **Historical Maximum Drawdown:** `{risk_data.get('max_drawdown', -22.5)}%`

---

## 5. Automated Compliance & Risk Disclaimer
*This automated report is generated by the CSAIML AI Financial Analysis & Investment Intelligence System for informational, research, and educational purposes. Historical performance and machine learning predictive models do not guarantee future returns. Always perform independent due diligence.*
"""
        return md_content

    def generate_pdf_report(
        self,
        ticker: str,
        company_name: str,
        quote: Dict[str, Any],
        fundamentals: Dict[str, Any],
        verdict_data: Dict[str, Any],
        dl_forecast_data: Dict[str, Any],
        risk_data: Dict[str, Any],
        sentiment_data: Dict[str, Any]
    ) -> Path:
        """
        Generates and saves a styled institutional PDF report.
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        clean_ticker = ticker.replace("^", "").replace("=", "_").replace(".", "_")
        pdf_filename = f"Research_Report_{clean_ticker}_{timestamp}.pdf"
        pdf_path = self.reports_dir / pdf_filename

        try:
            from reportlab.lib.pagesizes import letter
            from reportlab.lib import colors
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

            doc = SimpleDocTemplate(str(pdf_path), pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
            styles = getSampleStyleSheet()
            elements = []

            # Custom Styles
            title_style = ParagraphStyle("ReportTitle", parent=styles["Heading1"], fontSize=20, leading=24, textColor=colors.HexColor("#0F172A"))
            subtitle_style = ParagraphStyle("ReportSub", parent=styles["Normal"], fontSize=10, textColor=colors.HexColor("#64748B"), spaceAfter=12)
            section_style = ParagraphStyle("SectionHead", parent=styles["Heading2"], fontSize=14, leading=18, textColor=colors.HexColor("#1E293B"), spaceBefore=10, spaceAfter=6)
            body_style = ParagraphStyle("BodyTextCustom", parent=styles["Normal"], fontSize=9.5, leading=13, textColor=colors.HexColor("#334155"))

            # Header
            elements.append(Paragraph(f"<b>AI INVESTMENT INTELLIGENCE RESEARCH NOTE</b>", title_style))
            elements.append(Paragraph(f"<b>Asset:</b> {company_name} ({ticker}) | <b>Date:</b> {datetime.now().strftime('%B %d, %Y')} | <b>System:</b> CSAIML AI Engine", subtitle_style))
            elements.append(Spacer(1, 10))

            # Verdict Banner Table
            verdict = verdict_data.get("verdict", "BUY")
            score = verdict_data.get("composite_score", 75.0)
            verdict_color = colors.HexColor("#10B981") if "BUY" in verdict else colors.HexColor("#EF4444") if "SELL" in verdict else colors.HexColor("#F59E0B")

            verdict_table_data = [
                [
                    Paragraph(f"<b>RECOMMENDATION</b><br/><font size=16 color='{verdict_color.hexval()}'><b>{verdict}</b></font>", body_style),
                    Paragraph(f"<b>COMPOSITE AI SCORE</b><br/><font size=16><b>{score} / 100</b></font>", body_style),
                    Paragraph(f"<b>SPOT PRICE</b><br/><font size=16><b>${quote.get('current_price', 150.0)}</b></font>", body_style),
                    Paragraph(f"<b>30D FORECAST</b><br/><font size=16><b>{dl_forecast_data.get('expected_return_30d', 4.5)}%</b></font>", body_style)
                ]
            ]
            v_table = Table(verdict_table_data, colWidths=[130, 130, 130, 130])
            v_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8)
            ]))
            elements.append(v_table)
            elements.append(Spacer(1, 14))

            # Executive Summary
            elements.append(Paragraph("<b>1. Executive Summary</b>", section_style))
            elements.append(Paragraph(verdict_data.get("summary_description", "Comprehensive quantitative evaluation."), body_style))
            elements.append(Spacer(1, 10))

            # Predictive & Fundamental Metrics Table
            elements.append(Paragraph("<b>2. Key Quantitative & Valuation Metrics</b>", section_style))
            metrics_table_data = [
                ["Metric Category", "Indicator", "Value", "Benchmark / Status"],
                ["Machine Learning", "Tree Classifier Bullish Prob", str(verdict_data.get("component_breakdown", {}).get("ML Classification Probability", "65%")), "Supervised Trend Signal"],
                ["Deep Learning", "30-Day Trajectory Forecast", f"{dl_forecast_data.get('expected_return_30d', 4.5)}%", f"RMSE: {dl_forecast_data.get('metrics', {}).get('RMSE', 2.1)}"],
                ["NLP Sentiment", "Headline Polarity Index", str(sentiment_data.get("overall_label", "BULLISH")), f"{sentiment_data.get('bullish_pct', 70)}% Positive News Density"],
                ["Fundamentals", "Financial Health Score", f"{fundamentals.get('health_score', 80)} / 100", "Solvency & Profitability"],
                ["Fundamentals", "Trailing P/E Ratio", str(fundamentals.get("ratios", {}).get("Trailing P/E", "N/A")), "Valuation Multiple"],
                ["Risk Profile", "30-Day 95% Value-at-Risk", f"-{risk_data.get('var_95_30d', 9.2)}%", "Downside Variance"],
                ["Risk Profile", "Annualized Sharpe Ratio", str(risk_data.get("sharpe_ratio", 1.45)), f"Sortino: {risk_data.get('sortino_ratio', 1.85)}"]
            ]
            m_table = Table(metrics_table_data, colWidths=[110, 170, 110, 130])
            m_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F172A")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5)
            ]))
            elements.append(m_table)
            elements.append(Spacer(1, 14))

            # Disclaimer
            elements.append(Paragraph("<b>3. Research Disclaimer</b>", section_style))
            elements.append(Paragraph(
                "This report is generated automatically by the CSAIML AI Financial Analysis System for research and educational purposes. "
                "Forecasts and ratings do not constitute personalized financial advice.",
                body_style
            ))

            doc.build(elements)
            logger.info(f"Generated institutional PDF report at {pdf_path}")
            return pdf_path

        except Exception as e:
            logger.warning(f"ReportLab PDF generation error: {e}. Writing markdown file fallback.")
            # Fallback: Save markdown version
            md_path = self.reports_dir / f"Research_Report_{clean_ticker}_{timestamp}.md"
            md_content = self.generate_markdown_report(
                ticker, company_name, quote, fundamentals, verdict_data, dl_forecast_data, risk_data, sentiment_data
            )
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(md_content)
            return md_path
